//! Named parameter presets.
//!
//! Presets are deliberately data-only: a list of `(key, value)` overrides
//! applied through the schema. They are used by the CLI (`--preset`), the Web
//! UI dropdown and the integration tests, which guarantees a preset cannot
//! reference a parameter that no block owns.

/// One named world archetype.
#[derive(Clone, Copy, Debug)]
