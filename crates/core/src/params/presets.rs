/// Finds a preset by key.
#[must_use]
pub fn find(key: &str) -> Option<&'static Preset> {
    PRESETS.iter().find(|p| p.key == key)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_are_unique_and_findable() {
        let mut keys: Vec<&str> = PRESETS.iter().map(|p| p.key).collect();
        keys.sort_unstable();
        let n = keys.len();
        keys.dedup();
        assert_eq!(keys.len(), n);
        for p in PRESETS {
            assert!(find(p.key).is_some());
        }
    }

    #[test]
    fn presets_are_not_empty_and_have_unique_override_keys() {
        for p in PRESETS {
            assert!(!p.overrides.is_empty(), "{} has no overrides", p.key);
            let mut keys: Vec<&str> = p.overrides.iter().map(|(k, _)| *k).collect();
            keys.sort_unstable();
            let n = keys.len();
            keys.dedup();
            assert_eq!(keys.len(), n, "{} has duplicate override keys", p.key);
        }
    }
}
